"""
Report Generator for comprehensive conversion and strict validation audits.
"""
from typing import Dict, Any

class ReportGenerator:
    def generate_markdown(self, report_data: Dict[str, Any]) -> str:
        status = report_data.get("validation_status", "PASS")
        status_badge = "✅ PASS" if status == "PASS" else ("⚠️ PASS WITH WARNINGS" if status == "PASS_WITH_WARNINGS" else "❌ FAILED")
        
        md = [
            "# Universal UiPath-to-PAD Conversion Audit Report",
            f"**Validation Status:** {status_badge}",
            "",
            "## 1. Project Profile & Auto-Detected Complexity",
            f"- **Project Name:** `{report_data.get('project_name', 'Unknown')}`",
            f"- **Entry Point:** `{report_data.get('entry_point', 'Main.xaml')}`",
            f"- **Auto-Detected Complexity:** `{report_data.get('complexity_rating', 'SIMPLE')}` (Score: {report_data.get('complexity_score', 0)})",
            f"- **Workflows Discovered:** {report_data.get('workflow_count', 0)}",
            f"- **Total Activities:** {report_data.get('total_activities', 0)}",
            f"- **Generated PAD Action Count:** {report_data.get('action_count', 0)}",
            f"- **Archetype:** `{'⚠️ Blueprint / Scaffold Template' if report_data.get('is_scaffold') else '⚡ Executable Automation'}`",
            "",
            "## 2. Activity Conversion Coverage",
            f"- **Conversion Coverage:** {report_data.get('coverage_pct', 100.0)}%",
            f"- **Supported Activities:** {report_data.get('supported_count', 0)}",
            f"- **Unsupported Activities:** {len(report_data.get('unsupported_list', []))}",
            ""
        ]

        if report_data.get("unsupported_list"):
            md.append("### Unsupported Activities Encountered:")
            for item in report_data["unsupported_list"]:
                md.append(f"- `{item.get('type')}`: {item.get('reason', 'No direct equivalent')}")
            md.append("")

        if report_data.get("validation_errors"):
            md.append("## 3. Strict Validation Errors (Blocking)")
            for err in report_data["validation_errors"]:
                md.append(f"- 🔴 {err}")
            md.append("")

        if report_data.get("validation_warnings"):
            md.append("## 4. Migration Diagnostics & Warnings")
            for w in report_data["validation_warnings"]:
                md.append(f"- 🟡 {w}")
            md.append("")

        md.append("---")
        md.append("*Generated by Universal UiPath-to-PAD Conversion Engine (PAD 2.74 Classic Robin)*")
        return "\n".join(md)

    def generate_html(self, report_data: Dict[str, Any]) -> str:
        md = self.generate_markdown(report_data)
        return f"""<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<title>Conversion Report - {report_data.get('project_name', 'UiPath Project')}</title>
<style>
body {{ font-family: Segoe UI, sans-serif; margin: 30px; line-height: 1.6; color: #333; }}
h1, h2, h3 {{ color: #005a9e; }}
code {{ background: #f0f0f0; padding: 2px 6px; border-radius: 4px; }}
.pass {{ color: green; font-weight: bold; }}
.fail {{ color: red; font-weight: bold; }}
.warn {{ color: orange; font-weight: bold; }}
</style>
</head>
<body>
<pre>{md}</pre>
</body>
</html>"""

